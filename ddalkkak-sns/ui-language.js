  function resolveLanguage(value) {
    const requested = String(value || "auto").toLowerCase();
    if (requested !== "auto" && SUPPORTED.includes(requested)) return requested;
    const browserLanguage = String(navigator.language || "ko").slice(0, 2).toLowerCase();
    return SUPPORTED.includes(browserLanguage) ? browserLanguage : "ko";
  }

  function applyLanguage(value) {
    const language = resolveLanguage(value);
    document.documentElement.lang = language;
    const dictionary = STRINGS[language] || {};
    for (const node of document.querySelectorAll("[data-i18n]")) {
      const key = node.getAttribute("data-i18n");
      const text = dictionary[key];
      if (!text) continue;
      node.textContent = text;
    }
    for (const node of document.querySelectorAll("[data-i18n-placeholder]")) {
      const key = node.getAttribute("data-i18n-placeholder");
      const text = dictionary[key];
      if (text) node.setAttribute("placeholder", text);
    }
    for (const node of document.querySelectorAll("[data-i18n-option]")) {
      const text = dictionary[node.getAttribute("data-i18n-option")];
      if (text) node.textContent = text;
    }
    for (const [id, key] of Object.entries(ID_KEYS)) {
      const text = dictionary[key];
      const node = document.getElementById(id);
      if (!node || !text) continue;
      if (node.tagName === "SELECT") {
        const option = node.querySelector("option[value='blog'], option:first-child");
        if (node.id === "postingModeInput" && option) option.textContent = text;
        continue;
      }
      if (node.tagName === "TEXTAREA" || node.tagName === "INPUT") node.setAttribute("placeholder", text);
      else node.textContent = text;
    }
    for (const label of document.querySelectorAll(".field-label, .field-group")) {
      const key = LABEL_KEYS[String(label.textContent || "").trim()];
      const translated = dictionary[key];
      if (translated) label.textContent = translated;
    }
    const modeOptions = { blog: dictionary["postingMode.blog"], instagram: dictionary["postingMode.instagram"], threads: dictionary["postingMode.threads"] };
    for (const [optionValue, label] of Object.entries(modeOptions)) {
      const option = document.querySelector(`#postingModeInput option[value='${optionValue}']`);
      if (option && label) option.textContent = label;
    }
    return language;
  }

  globalThis.ddalkkakLanguage = Object.freeze({ applyLanguage, resolveLanguage });
